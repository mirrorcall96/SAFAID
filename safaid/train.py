#!/usr/bin/env python3
"""Script version of training/Train.ipynb (full fine-tuning of Qwen3-VL-4B-Instruct).

Training code, hyper-parameters and the augmentation pipeline are copied unchanged from the
notebook (including the albumentations 1.x argument names). Additions only:
  --seed          seeds python/numpy/torch/albumentations and the Trainer
  --train_prompt  'investigative' (SAFAID, notebook default) or 'category' (CatAID template, Train-13.ipynb)
  --stop_step     stop at this optimizer step of the 3-epoch cosine schedule (paper model = checkpoint-1600)
  ablation / baseline options (defaults reproduce the SAFAID runs exactly):
  --train_prompt vanilla   plain question without the investigative framing (Table 2 ablation)
  --aug_mode      fake_only (SAFAID) | uniform (same pipeline on real and fake) | none
  --schedule_steps fix the cosine schedule length in optimizer steps (3750 = SAFAID's 3 epochs x 1250), so
                  ablations with a different number of samples follow the identical LR trajectory
  --method qlora  4-bit QLoRA with the Train-13.ipynb adapter config (r=16, alpha=16, all layers, LR 2e-4, adamw_8bit)
  file logging    config.json, loss.csv, progress.json, trainer_state.json in the run folder
The training subset is the fixed, seeded manifest instead of os.listdir()[:100] (not reproducible).
"""
