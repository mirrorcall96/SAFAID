class FileLogger(TrainerCallback):
    def on_log(self, a, state, control, logs=None, **kw):
        logs = logs or {}
        el = time.time() - T0
        mem = torch.cuda.max_memory_allocated() / 1e9
        if "loss" in logs:
            with open(LOSS_CSV, "a") as f:
                f.write(f"{state.global_step},{logs.get('epoch', state.epoch)},{logs['loss']},"
                        f"{logs.get('learning_rate', '')},{logs.get('grad_norm', '')},{el:.1f},{mem:.2f}\n")
        s_per_step = el / max(state.global_step, 1)
        json.dump({"phase": "train", "step": state.global_step, "stop_step": args.stop_step,
                   "epoch": state.epoch, "last_loss": logs.get("loss"), "elapsed_min": round(el / 60, 1),
                   "s_per_step": round(s_per_step, 3),
                   "eta_min": round((args.stop_step - state.global_step) * s_per_step / 60, 1),
                   "max_mem_gb": round(mem, 2), "updated_utc": time.strftime("%H:%M:%S", time.gmtime())},
                  open(os.path.join(RUN_DIR, "progress.json"), "w"), indent=1)


class StopAtStep(TrainerCallback):
    def on_step_end(self, a, state, control, **kw):
        if state.global_step >= args.stop_step:
            control.should_save = True
            control.should_training_stop = True
        return control


