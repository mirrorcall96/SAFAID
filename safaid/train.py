def create_ccp_prompt(category):
    if args.train_prompt == "category":
        # CatAID template, as in Train-13.ipynb
        return f"This is an image of a {category}. Is this image generated by AI, or is it a real image?"
    if args.train_prompt == "vanilla":
        return "Is this image generated by AI, or is it a real image?"
    return f"This is an image that is under investigation. Is this image generated by AI, or is it a real image?"


def create_response(label):
    """Create response based on label."""
    if label == "real":
        return "This is a real image."
    else:
        return "This is an AI-generated image."


def load_manifest_samples():
    samples = []
    with open(args.manifest) as f:
        for row in csv.DictReader(f):
            if row["split"] != "train":
                continue
            samples.append({
                "image_path": os.path.join(args.data_dir, row["name"]),
                "category": row["category"],
                "label": "real" if row["label"] == "0_real" else "fake",
            })
    random.shuffle(samples)
    print(f"Loaded {len(samples)} samples for train")
    return samples


train_samples = load_manifest_samples()
