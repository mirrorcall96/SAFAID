#!/usr/bin/env python3
"""Evaluate one model on the post-cutoff contamination set.

A thin stand-alone copy of safaid/eval.py: it imports NOTHING from eval.py, but the inference code is
copied verbatim (PROMPTS, unsloth FastVisionModel 16-bit load, AutoProcessor with the same fallback, left
padding, ImageListDataset/collate_fn, batch_detect with generate(max_new_tokens=50, temperature=0.1,
do_sample=False), parse, counts). --check_against <eval.py> compares those pieces as TEXT (the file is read,
never imported) and records IDENTICAL / DIFFERENT in metrics_<tag>.json.

Differences to eval.py are in bookkeeping only:
  * ROOTS also maps zip "postcutoff" -> <data_root>/postcutoff (or --postcutoff_root)
  * outputs are preds_<tag>.csv / metrics_<tag>.json / EVAL_DONE_<tag> in --run_dir (a NEW directory, never
    a Table-1 run dir); preds keep the full response text (eval.py truncates it to 200 characters)
  * metrics: every generator (table1_row of benchmark PostCutoff or PostCutoffModelPreCutoffVAE) is scored
    on its fakes plus the shared "real pool post-cutoff" (benchmark PostCutoffReal): acc, balanced accuracy
    (real_acc + fake_acc) / 2, real_acc, fake_acc, unknowns, plus per-group means of the per-generator
    numbers. The two groups are never averaged together.
  * the share of responses that are not exactly one of the two trained strings is reported.
Unparseable answers count as errors (as in eval.py). Resumable: images already in preds_<tag>.csv are skipped.

    python contamination/eval_post.py --manifest $SAFAID_DATA/postcutoff/postcutoff_manifest.csv \
        --model_path $SAFAID_RUNS/r11_.../model/checkpoint-1600 --run_dir $SAFAID_RUNS/postcutoff/r11_... \
        --test_prompt investigative --tag investigative --data_root $SAFAID_DATA --check_against safaid/eval.py
"""
import os, sys, csv, json, time, argparse, collections

p = argparse.ArgumentParser()
p.add_argument("--manifest", required=True)
p.add_argument("--model_path", required=True)
p.add_argument("--run_dir", required=True)
p.add_argument("--test_prompt", choices=["investigative", "vanilla"], required=True)
p.add_argument("--tag", default=None, help="suffix of preds_/metrics_/EVAL_DONE_ (default: the test prompt)")
p.add_argument("--data_root", default=os.environ.get("SAFAID_DATA", os.path.join(os.environ.get("SAFAID_WORKDIR", "/workspace/safaid"), "data")))
p.add_argument("--postcutoff_root", default=None, help="default: <data_root>/postcutoff")
p.add_argument("--batch_size", type=int, default=128)
p.add_argument("--limit_per_row", type=int, default=0, help="smoke test: only N images per label per row")
p.add_argument("--check_against", default=None, help="path of eval.py; compare the inference code as text")
p.add_argument("--check_only", action="store_true", help="run --check_against and exit (no model, no data)")
args = p.parse_args()

PROMPTS = {
    "investigative": "This is an image that is under investigation. Is this image generated by AI, or is it a real image?",
    # CatAID deploys its category-trained model without the category prefix (CatAID §4.1)
    "vanilla": "Is this image generated by AI, or is it a real image?",
}
prompt_text = PROMPTS[args.test_prompt]
ROOTS = {"CNN_synth_testset.zip": os.path.join(args.data_root, "forensynths"),
         "diffusion_datasets.zip": args.data_root,
         "postcutoff": args.postcutoff_root or os.path.join(args.data_root, "postcutoff")}
GROUPS = ["PostCutoff", "PostCutoffModelPreCutoffVAE"]  # reported separately, never pooled
REAL_BENCHMARK = "PostCutoffReal"
CANONICAL = ("This is a real image.", "This is an AI-generated image.")


def check_inference_code(eval_py):
    """Compare this file's inference code with eval.py's, as text (eval.py is read, not imported)."""
    import ast
    def pieces(path):
        src = open(path).read()
        tree = ast.parse(src)
        out = {}
        for node in tree.body:
            if isinstance(node, (ast.FunctionDef, ast.ClassDef)) and node.name in (
                    "ImageListDataset", "collate_fn", "batch_detect", "parse", "counts"):
                out[node.name] = ast.get_source_segment(src, node)
            if isinstance(node, ast.Assign) and any(getattr(t, "id", None) == "PROMPTS" for t in node.targets):
                out["PROMPTS"] = ast.get_source_segment(src, node)
        lines = src.splitlines()
        try:
            i = next(k for k, l in enumerate(lines) if l.startswith("model, tokenizer = FastVisionModel.from_pretrained("))
            j = next(k for k in range(i, len(lines))
                     if lines[k].strip() == "processor.tokenizer.pad_token_id = processor.tokenizer.eos_token_id")
            out["model_load"] = "\n".join(x.rstrip() for x in lines[i:j + 1])
        except StopIteration:
            out["model_load"] = None
        imp = [l for l in lines if l in ("import torch", "from PIL import Image", "from torch.utils.data import DataLoader, Dataset",
                                        "from unsloth import FastVisionModel", "from transformers import AutoProcessor")]
        out["imports"] = "\n".join(imp)
        return out
    if not os.path.exists(eval_py):
        print(f"inference code check skipped: {eval_py} not found", flush=True)
        return f"not checked ({eval_py} not found)"
    mine, theirs = pieces(os.path.abspath(__file__)), pieces(eval_py)
    diff = sorted(k for k in set(mine) | set(theirs) if mine.get(k) != theirs.get(k))
    status = "IDENTICAL" if not diff else "DIFFERENT: " + ", ".join(diff)
    print(f"inference code vs {eval_py}: {status}", flush=True)
    return status


CODE_CHECK = check_inference_code(args.check_against) if args.check_against else "not checked"
if args.check_only:
    sys.exit(0 if CODE_CHECK == "IDENTICAL" else 1)

# ---- image list from manifest ----
rows = []
per = collections.Counter()
with open(args.manifest) as f:
    for r in csv.DictReader(f):
        if r["table1_row"] == "(not in Table 1)":
            continue
        k = (r["table1_row"], r["label"])
        per[k] += 1
        if args.limit_per_row and per[k] > args.limit_per_row:
            continue
        r["path"] = os.path.join(ROOTS[r["zip"]], r["member"])
        rows.append(r)
missing = [r["path"] for r in rows if not os.path.exists(r["path"])]
assert not missing, f"{len(missing)} eval images missing, e.g. {missing[:3]}"
assert any(r["benchmark"] == REAL_BENCHMARK for r in rows), f"no {REAL_BENCHMARK} rows in {args.manifest}"

os.makedirs(args.run_dir, exist_ok=True)
TAG = (args.tag or args.test_prompt) + ("_smoke" if args.limit_per_row else "")
PREDS = os.path.join(args.run_dir, f"preds_{TAG}.csv")
METRICS = os.path.join(args.run_dir, f"metrics_{TAG}.json")
PROG = os.path.join(args.run_dir, "progress.json")
HEADER = ["benchmark", "table1_row", "folder", "subclass", "label", "path", "pred", "response"]
KEEP = ("benchmark", "table1_row", "folder", "subclass", "label", "pred", "response")
done = {}
if os.path.exists(PREDS):
    # resume: keep only complete rows for images in the manifest (a killed run can leave a partial last line)
    want = {r["path"] for r in rows}
    with open(PREDS, newline="") as f:
        good = [r for r in csv.DictReader(f) if r.get("path") in want and r.get("pred") in ("real", "fake", "unknown")]
    with open(PREDS + ".tmp", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=HEADER); w.writeheader(); w.writerows({k: r.get(k, "") for k in HEADER} for r in good)
    os.replace(PREDS + ".tmp", PREDS)
    for r in good:
        done[r["path"]] = {k: r.get(k, "") for k in KEEP}
else:
    with open(PREDS, "w", newline="") as f:
        csv.writer(f).writerow(HEADER)

# ---- model: identical to the eval notebook ----
import torch
from PIL import Image
from torch.utils.data import DataLoader, Dataset
from unsloth import FastVisionModel
from transformers import AutoProcessor

model, tokenizer = FastVisionModel.from_pretrained(
    args.model_path, max_seq_length=4096, load_in_4bit=False, load_in_8bit=False, load_in_16bit=True)
FastVisionModel.for_inference(model)
try:
    processor = AutoProcessor.from_pretrained(args.model_path)
except Exception:
    processor = AutoProcessor.from_pretrained("unsloth/Qwen3-VL-4B-Instruct")
processor.tokenizer.padding_side = "left"
if processor.tokenizer.pad_token is None:
    processor.tokenizer.pad_token = processor.tokenizer.eos_token
    processor.tokenizer.pad_token_id = processor.tokenizer.eos_token_id


class ImageListDataset(Dataset):
    def __init__(self, items):
        self.items = items

    def __len__(self):
        return len(self.items)

    def __getitem__(self, idx):
        r = self.items[idx]
        try:
            return {"image": Image.open(r["path"]).convert("RGB"), "row": r, "valid": True}
        except Exception:
            return {"image": None, "row": r, "valid": False}


def collate_fn(batch):
    return batch


def batch_detect(images):
    conversations = [[{"role": "user", "content": [{"type": "image", "image": img}, {"type": "text", "text": prompt_text}]}]
                     for img in images]
    text_prompts = [processor.apply_chat_template(c, tokenize=False, add_generation_prompt=True) for c in conversations]
    inputs = processor(text=text_prompts, images=images, padding=True, return_tensors="pt").to(model.device)
    with torch.no_grad():
        output_ids = model.generate(**inputs, max_new_tokens=50, temperature=0.1, do_sample=False)
    generated_ids = [o[len(i):] for i, o in zip(inputs.input_ids, output_ids)]
    return processor.batch_decode(generated_ids, skip_special_tokens=True, clean_up_tokenization_spaces=False)


def parse(response):
    r = response.lower()
    if "ai-generated" in r or "ai generated" in r or "fake" in r:
        return "fake"
    elif "real" in r:
        return "real"
    return "unknown"


def record(r, pred, resp):
    return {"benchmark": r["benchmark"], "table1_row": r["table1_row"], "folder": r.get("folder", ""),
            "subclass": r["subclass"], "label": r["label"], "pred": pred, "response": resp}


def run_items(items, bs, name):
    items = [r for r in items if r["path"] not in done]
    if not items:
        return
    loader = DataLoader(ImageListDataset(items), batch_size=bs, shuffle=False, collate_fn=collate_fn, num_workers=8)
    t0, n = time.time(), 0
    with open(PREDS, "a", newline="") as f:
        w = csv.writer(f)
        for batch in loader:
            ok = [b for b in batch if b["valid"]]
            for b in batch:
                if not b["valid"]:
                    r = b["row"]
                    w.writerow([r["benchmark"], r["table1_row"], r.get("folder", ""), r["subclass"], r["label"], r["path"],
                                "unknown", "<load error>"])
                    done[r["path"]] = record(r, "unknown", "<load error>")
            sub = bs
            i = 0
            while i < len(ok):
                chunk = ok[i:i + sub]
                try:
                    responses = batch_detect([b["image"] for b in chunk])
                except torch.cuda.OutOfMemoryError:
                    torch.cuda.empty_cache()
                    if sub == 1:
                        raise
                    sub = max(1, sub // 2)
                    print(f"OOM on {name}: retry with batch {sub}", flush=True)
                    continue
                for b, resp in zip(chunk, responses):
                    r = b["row"]
                    pred = parse(resp)
                    text = resp.replace("\r", " ").replace("\n", " ")  # full text (eval.py keeps only [:200])
                    w.writerow([r["benchmark"], r["table1_row"], r.get("folder", ""), r["subclass"], r["label"], r["path"],
                                pred, text])
                    done[r["path"]] = record(r, pred, text)
                i += len(chunk)
            f.flush()
            n += len(batch)
            el = time.time() - t0
            json.dump({"phase": f"eval_post[{TAG}]", "dataset": name, "done": n, "of": len(items),
                       "img_per_s": round(n / max(el, 1e-6), 1), "total_done": len(done), "total": len(rows),
                       "updated_utc": time.strftime("%H:%M:%S", time.gmtime())}, open(PROG, "w"), indent=1)
    print(f"{name}: {n} images in {time.time() - t0:.0f}s", flush=True)


def counts(preds):
    tp = sum(1 for d in preds if d["label"] == "1_fake" and d["pred"] == "fake")
    tn = sum(1 for d in preds if d["label"] == "0_real" and d["pred"] == "real")
    nf = sum(1 for d in preds if d["label"] == "1_fake")
    nr = sum(1 for d in preds if d["label"] == "0_real")
    unk = sum(1 for d in preds if d["pred"] == "unknown")
    return {"n": nf + nr, "n_real": nr, "n_fake": nf, "acc": round(100 * (tp + tn) / max(nf + nr, 1), 2),
            "real_acc": round(100 * tn / max(nr, 1), 2), "fake_acc": round(100 * tp / max(nf, 1), 2),
            "tp": tp, "tn": tn, "fp": nr - tn - sum(1 for d in preds if d["label"] == "0_real" and d["pred"] == "unknown"),
            "fn": nf - tp - sum(1 for d in preds if d["label"] == "1_fake" and d["pred"] == "unknown"), "unknown": unk}


def scored(preds):
    """eval.py's counts() plus balanced accuracy = (real_acc + fake_acc) / 2 (from unrounded rates)."""
    c = counts(preds)
    c["balanced_acc"] = round(50 * (c["tn"] / max(c["n_real"], 1) + c["tp"] / max(c["n_fake"], 1)), 2)
    return c


def noncanonical(preds):
    n = len(preds)
    k = sum(1 for d in preds if d.get("response", "").strip() not in CANONICAL)
    return {"n": n, "noncanonical": k, "share_noncanonical": round(100 * k / max(n, 1), 2)}


def mean(xs):
    return round(sum(xs) / len(xs), 2) if xs else None


def write_metrics():
    reals = [d for d in done.values() if d["benchmark"] == REAL_BENCHMARK and d["label"] == "0_real"]
    fakes = collections.defaultdict(list)
    for d in done.values():
        if d["benchmark"] in GROUPS and d["label"] == "1_fake":
            fakes[(d["benchmark"], d["table1_row"])].append(d)
    out = {"model_path": args.model_path, "test_prompt": prompt_text, "test_prompt_name": args.test_prompt, "tag": TAG,
           "manifest": os.path.abspath(args.manifest), "inference_code_check": CODE_CHECK,
           "parse": "eval.py parse() (fake keywords checked first); unknown counts as an error",
           "real_pool": {**counts(reals), "benchmark": REAL_BENCHMARK}, "generators": {}, "groups": {},
           "response_format": {"canonical": list(CANONICAL), "real_pool": noncanonical(reals)}}
    for (bench, row), fk in sorted(fakes.items()):
        out["generators"][row] = {"group": bench, "folder": fk[0].get("folder", ""), **scored(fk + reals)}
        out["response_format"][row] = noncanonical(fk)
    for g in GROUPS:
        gens = [row for row, v in out["generators"].items() if v["group"] == g]
        if not gens:
            continue
        gv = [out["generators"][row] for row in gens]
        out["groups"][g] = {"generators": gens, "n_generators": len(gens),
                            "mean_balanced_acc": mean([v["balanced_acc"] for v in gv]),
                            "mean_fake_acc": mean([v["fake_acc"] for v in gv]),
                            "mean_acc": mean([v["acc"] for v in gv]),
                            "real_acc": out["real_pool"]["real_acc"]}
    alls = list(done.values())
    out["response_format"]["all"] = noncanonical(alls)
    json.dump(out, open(METRICS, "w"), indent=1)
    return out


groups = collections.OrderedDict()
for r in rows:
    groups.setdefault(r["table1_row"], []).append(r)
# the shared real pool first, then each generator
order = [g for g in groups if any(x["benchmark"] == REAL_BENCHMARK for x in groups[g])] + \
        [g for g in groups if not any(x["benchmark"] == REAL_BENCHMARK for x in groups[g])]
for g in order:
    run_items(groups[g], args.batch_size, g)
    write_metrics()

m = write_metrics()
print(json.dumps({row: {k: v[k] for k in ("group", "balanced_acc", "real_acc", "fake_acc", "unknown")}
                  for row, v in m["generators"].items()}, indent=1))
print(json.dumps({"groups": m["groups"], "noncanonical_all": m["response_format"]["all"]}, indent=1))
if not args.limit_per_row:
    open(os.path.join(args.run_dir, f"EVAL_DONE_{TAG}"), "w").write("ok\n")
